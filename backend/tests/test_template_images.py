"""Images bucket and logo routes in ``infra/template.yaml`` (RN012).

The bucket is private (no public access, no ACLs, TLS only), encrypted with
SSE-S3, unversioned and named by CloudFormation; only the logo functions reach
it, each with the single S3 action it uses on ``logos/*``.
"""

from pathlib import Path
from typing import Any

import pytest
from cfnlint.decode import decode

TEMPLATE = Path(__file__).resolve().parents[2] / "infra" / "template.yaml"
LOGOS_ARN = {"Fn::Sub": "${ImagesBucket.Arn}/logos/*"}
SETTINGS_ARN = {"Fn::GetAtt": ["SettingsTable", "Arn"]}


@pytest.fixture(scope="module")
def template() -> dict[str, Any]:
    parsed, errors = decode(str(TEMPLATE))
    assert not errors, errors
    return parsed


def _bucket(template: dict[str, Any]) -> dict[str, Any]:
    buckets = [
        resource
        for resource in template["Resources"].values()
        if resource["Type"] == "AWS::S3::Bucket"
    ]
    assert len(buckets) == 1
    assert template["Resources"]["ImagesBucket"] is buckets[0]
    return buckets[0]


def test_rn012_images_bucket_is_private_and_encrypted(template: dict[str, Any]) -> None:
    properties = _bucket(template)["Properties"]

    assert properties["PublicAccessBlockConfiguration"] == {
        "BlockPublicAcls": True,
        "BlockPublicPolicy": True,
        "IgnorePublicAcls": True,
        "RestrictPublicBuckets": True,
    }
    assert properties["BucketEncryption"] == {
        "ServerSideEncryptionConfiguration": [
            {"ServerSideEncryptionByDefault": {"SSEAlgorithm": "AES256"}}
        ]
    }
    assert properties["OwnershipControls"] == {
        "Rules": [{"ObjectOwnership": "BucketOwnerEnforced"}]
    }
    # Name generated by CloudFormation; no versioning, website or CORS.
    assert not {
        "BucketName",
        "VersioningConfiguration",
        "WebsiteConfiguration",
        "CorsConfiguration",
    } & set(properties)


@pytest.mark.parametrize(("is_prod", "expected"), [(False, "Delete"), (True, "Retain")])
def test_rn012_images_bucket_follows_the_tables_retention(
    template: dict[str, Any], is_prod: bool, expected: str
) -> None:
    bucket = _bucket(template)
    for policy in ("DeletionPolicy", "UpdateReplacePolicy"):
        condition, prod, dev = bucket[policy]["Fn::If"]
        assert condition == "IsProd"
        assert (prod if is_prod else dev) == expected, policy


def test_rn012_images_bucket_denies_requests_without_tls(template: dict[str, Any]) -> None:
    policies = [
        resource["Properties"]
        for resource in template["Resources"].values()
        if resource["Type"] == "AWS::S3::BucketPolicy"
    ]

    assert len(policies) == 1
    assert policies[0]["Bucket"] == {"Ref": "ImagesBucket"}
    statements = policies[0]["PolicyDocument"]["Statement"]
    assert statements == [
        {
            "Sid": "DenyInsecureTransport",
            "Effect": "Deny",
            "Principal": "*",
            "Action": "s3:*",
            "Resource": [
                {"Fn::GetAtt": ["ImagesBucket", "Arn"]},
                {"Fn::Sub": "${ImagesBucket.Arn}/*"},
            ],
            "Condition": {"Bool": {"aws:SecureTransport": "false"}},
        }
    ]


def _granted(function: dict[str, Any]) -> set[tuple[str, str]]:
    granted: set[tuple[str, str]] = set()
    for policy in function["Properties"]["Policies"]:
        assert "Statement" in policy, "explicit statements only"
        for statement in policy["Statement"]:
            assert statement["Effect"] == "Allow"
            resource = statement["Resource"]
            assert resource in (LOGOS_ARN, SETTINGS_ARN), resource
            label = "logos/*" if resource == LOGOS_ARN else "SettingsTable"
            actions = statement["Action"]
            for action in [actions] if isinstance(actions, str) else actions:
                granted.add((action, label))
    return granted


@pytest.mark.parametrize(
    ("name", "method", "expected"),
    [
        (
            "PutLogoFunction",
            "PUT",
            {("s3:PutObject", "logos/*"), ("dynamodb:UpdateItem", "SettingsTable")},
        ),
        (
            "DeleteLogoFunction",
            "DELETE",
            {("s3:DeleteObject", "logos/*"), ("dynamodb:UpdateItem", "SettingsTable")},
        ),
        (
            "GetLogoFunction",
            "GET",
            {("s3:GetObject", "logos/*"), ("dynamodb:GetItem", "SettingsTable")},
        ),
    ],
)
def test_rn012_logo_routes_with_least_privilege(
    template: dict[str, Any], name: str, method: str, expected: set[tuple[str, str]]
) -> None:
    function = template["Resources"][name]
    api = function["Properties"]["Events"]["Api"]["Properties"]

    assert (api["Method"], api["Path"]) == (method, "/settings/logos/{slot}")
    assert api["ApiId"] == {"Ref": "HttpApi"}
    assert function["Properties"]["Handler"] == f"handlers.logos.{method.lower()}_logo"
    assert function["Properties"]["Environment"]["Variables"] == {
        "IMAGES_BUCKET": {"Ref": "ImagesBucket"}
    }
    assert _granted(function) == expected


def test_rn012_only_the_logo_functions_reach_the_bucket(template: dict[str, Any]) -> None:
    logo_functions = {"PutLogoFunction", "DeleteLogoFunction", "GetLogoFunction"}
    assert "IMAGES_BUCKET" not in template["Globals"]["Function"]["Environment"]["Variables"]
    for name, resource in template["Resources"].items():
        if resource["Type"] != "AWS::Serverless::Function" or name in logo_functions:
            continue
        properties = resource["Properties"]
        assert "IMAGES_BUCKET" not in properties.get("Environment", {}).get("Variables", {}), name
        for policy in properties.get("Policies", []):
            if not isinstance(policy, dict):
                continue
            assert not any(key.startswith("S3") for key in policy), (name, policy)
            for statement in policy.get("Statement", []):
                actions = statement["Action"]
                for action in [actions] if isinstance(actions, str) else actions:
                    assert not action.startswith("s3:"), (name, action)
