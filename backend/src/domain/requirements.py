"""Belt requirements: one record per evaluated item (RN017).

Every item belongs to a requirement profile (``domain.requirement_profiles``);
the seed items and the items written before profiles existed belong to the
main profile.
"""

import json
import uuid
from collections.abc import Iterable
from dataclasses import asdict, dataclass, replace
from enum import StrEnum
from functools import lru_cache
from pathlib import Path
from typing import Any

from domain import validation
from domain.belts import Belt, seed_belt_id
from domain.errors import ValidationError
from domain.requirement_profiles import MAIN_PROFILE_ID

_SEED_FILE = Path(__file__).resolve().parent.parent / "seed_data" / "requirements.json"
# Fixed namespace so seeded items get the same UUID on every deploy (idempotent seed).
_SEED_NAMESPACE = uuid.UUID("2b8f0c57-91d4-4a8e-b6f3-5e0d7c1a9f42")
# Fixed namespace of the items copied into a profile (``copied_requirement_id``).
_COPY_NAMESPACE = uuid.UUID("7d4e2a91-3c6b-4f08-9a15-c2e8b0f6d374")

MAX_CATEGORY = 60
MAX_TEXT = 2000
MAX_SORT_ORDER = 9999

MSG_REQUIREMENT_NOT_FOUND = "Requisito não encontrado"
MSG_REQUIREMENT_HAS_ANSWERS = "Requisito possui respostas registradas"
MSG_REQUIREMENT_LOCKED = (
    "Não é possível trocar a faixa ou o tipo de um requisito com respostas registradas"
)
MSG_DEFAULT_SORT_ORDER_FULL = (
    f"Ordem: a faixa já tem um item na ordem {MAX_SORT_ORDER}; informe a ordem do novo item"
)


class RequirementKind(StrEnum):
    """Theory or practice item; percentages are computed per kind (RN007)."""

    THEORY = "THEORY"
    PRACTICE = "PRACTICE"


@dataclass(frozen=True)
class Requirement:
    """An item evaluated in the exam for a belt."""

    id: str
    belt_id: str
    kind: RequirementKind
    category: str
    description: str
    expected_answer: str | None
    sort_order: int
    profile_id: str = MAIN_PROFILE_ID

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-serializable representation."""
        data = asdict(self)
        data["kind"] = self.kind.value
        return data


def seed_requirement_id(belt_name: str, sort_order: int) -> str:
    """Return the deterministic id of a seeded item."""
    return str(uuid.uuid5(_SEED_NAMESPACE, f"{belt_name}|{sort_order}"))


def copied_requirement_id(profile_id: str, source_requirement_id: str) -> str:
    """Return the deterministic id of an item copied into a profile.

    The same source item always lands on the same id in the same profile, so
    a copy that runs again (a retry, or a resume after a stop) never
    duplicates an item.
    """
    return str(uuid.uuid5(_COPY_NAMESPACE, f"{profile_id}|{source_requirement_id}"))


def copy_to_profile(source: Requirement, profile_id: str) -> Requirement:
    """Return the copy of an item in another profile: every field but the id and the profile.

    The answers counter (``answer_count``) is not part of the model, so a copy
    never carries the source's answers (RN006).
    """
    return replace(
        source,
        id=copied_requirement_id(profile_id, source.id),
        profile_id=profile_id,
    )


@lru_cache(maxsize=1)
def seed_requirements() -> tuple[Requirement, ...]:
    """Return the 692 items of Appendix A (generated by ``scripts/build_requirements_seed.py``)."""
    records = json.loads(_SEED_FILE.read_text(encoding="utf-8"))
    return tuple(
        Requirement(
            id=seed_requirement_id(record["belt"], record["sort_order"]),
            belt_id=seed_belt_id(record["belt"]),
            kind=RequirementKind(record["kind"]),
            category=record["category"],
            description=record["description"],
            expected_answer=record["expected_answer"],
            sort_order=record["sort_order"],
        )
        for record in records
    )


def sort_requirements(
    requirements: Iterable[Requirement], belts: Iterable[Belt]
) -> list[Requirement]:
    """Return items in graduation order of their belt, then in sheet order."""
    belt_order = {belt.id: belt.sort_order for belt in belts}
    return sorted(
        requirements,
        key=lambda req: (belt_order.get(req.belt_id, len(belt_order)), req.sort_order, req.id),
    )


def build_requirement(
    payload: dict[str, Any],
    belts_by_id: dict[str, Belt],
    *,
    requirement_id: str,
    default_sort_order: int,
    profile_id: str = MAIN_PROFILE_ID,
) -> Requirement:
    """Validate the fields of a new or edited item (RN017).

    Args:
        payload: Request body.
        belts_by_id: Every belt indexed by id; the item's belt must exist.
        requirement_id: Id of the item (new UUID or the existing one).
        default_sort_order: Order used when the payload omits ``sort_order``.
            It must also fit in 0 to ``MAX_SORT_ORDER`` (RN015); a belt whose last
            item is already at the maximum needs an explicit order.
        profile_id: Profile of the item, chosen by the caller (the body's
            ``profile_id`` is checked by ``domain.requirement_profiles``).

    Returns:
        The validated item.

    Raises:
        ValidationError: If a field is invalid, the belt does not exist or the
            default order would go past ``MAX_SORT_ORDER``.
    """
    belt_id = validation.required_str(payload, "belt_id", "Faixa", 64)
    if belt_id not in belts_by_id:
        raise ValidationError("Faixa: faixa não encontrada")
    if payload.get("sort_order") is None and default_sort_order > MAX_SORT_ORDER:
        raise ValidationError(MSG_DEFAULT_SORT_ORDER_FULL)
    return Requirement(
        id=requirement_id,
        belt_id=belt_id,
        kind=validation.enum_field(payload, "kind", "Tipo", RequirementKind),
        category=validation.required_str(payload, "category", "Categoria", MAX_CATEGORY),
        description=validation.required_str(payload, "description", "Descrição", MAX_TEXT),
        expected_answer=validation.optional_str(
            payload, "expected_answer", "Resposta esperada", MAX_TEXT
        ),
        sort_order=validation.int_field(
            payload,
            "sort_order",
            "Ordem",
            minimum=0,
            maximum=MAX_SORT_ORDER,
            default=default_sort_order,
        ),
        profile_id=profile_id,
    )
